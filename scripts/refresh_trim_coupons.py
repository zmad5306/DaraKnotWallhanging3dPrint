"""Replace only coupon veneer carriers; preserve core/caul assets and all poses.

Reads the existing coupon seating records to reconstruct the untooled cap.
The A2L/full-size carriers are deliberately not regenerated by this operation.
"""
import json
import math
import xml.etree.ElementTree as ET
import zipfile
import numpy as np
from shapely import affinity, union_all
from shapely.geometry import Point, LineString, box
from development_3mf import OUT, ROOT, save_json, sha, mesh_xml, tag, P, mesh, solid
from build_jointed_bambu_project import xml
from add_blue_ribbon_edge import artwork
from develop_m_veneer import (height_mesh, skin_bottom, texture, prism,
    screw_clearance_tools, screw_exclusion, seam_sample_panels)
from veneer_trim_carrier import fin_carrier


def refresh(name):
    path=OUT/(name+'.3mf')
    with zipfile.ZipFile(path) as z:files={n:z.read(n) for n in z.namelist()}
    before=dict(files)
    stage=json.loads(path.with_suffix('.json').read_text())
    seating_path=OUT/(name+'-seating.json');seating=json.loads(seating_path.read_text())
    outline=artwork((ROOT/'working/Dara-Photo-Frame-A1-Jointed.scad').read_text(),'letter_outline')
    sample=box(*seating['sample_bounds_mm']).intersection(outline)
    panels=seam_sample_panels(sample) if 'Seam' in name else [sample]
    root=ET.fromstring(files['3D/3dmodel.model']);cfg=ET.fromstring(files['Metadata/model_settings.config'])
    changed=[];checks=[]
    for region,row in zip(panels,seating['panels']):
        skin=solid(height_mesh(region,skin_bottom,texture(outline))[0])-screw_clearance_tools()
        points=np.array(row['pads_xy_mm']);d=points[1]-points[0]
        angle=math.degrees(math.atan2(d[1],d[0]))
        for k,p in enumerate(points[:2]):
            pocket=(LineString([(-.4,0),(.4,0)]) if k else Point(0,0)).buffer(1.35,quad_segs=12)
            pocket=affinity.translate(affinity.rotate(pocket,angle,origin=(0,0)),*p)
            skin-=prism(pocket,8.5,9.1)
        raw=mesh(skin)
        pose=np.array(row['carrier']['assembly_to_printer'])
        excluded=union_all([Point(*p).buffer(6) for p in points]).union(screw_exclusion())
        carried,evidence=fin_carrier(raw,region,skin_bottom,pose,excluded,height_mesh)
        record=next(r for r in stage['records'] if r['plate']==row['panel']+1)
        oid=str(record['object_id']);obj=root.find(tag('resources')).find(f"{tag('object')}[@id='{oid}']")
        co=obj.find(tag('components'))[0];pid=co.get('objectid');child_path=co.get('{'+P+'}path').lstrip('/')
        child=ET.fromstring(files[child_path]);resources=child.find(tag('resources'))
        resources.remove(resources.find(f"{tag('object')}[@id='{pid}']"))
        mesh_xml(resources,int(pid),carried,block_front=True,front_normal=pose[:3,:3]@np.array([0,0,1]))
        files[child_path]=xml(child);changed.append(child_path)
        stat=cfg.find(f"object[@id='{oid}']/part[@id='{pid}']/mesh_stat")
        stat.set('face_count',str(len(carried.faces)))
        t=np.array(record['assembly_to_printer']);v=carried.vertices@t[:3,:3].T+t[:3,3]
        record['body_bounds_mm']=[v.min(axis=0).tolist(),v.max(axis=0).tolist()]
        row['carrier']=evidence
        checks.append(dict(panel=row['panel'],raw_flat_back_z_mm=float(raw.bounds[0,2]),
                           revision=evidence['revision'],raw_volume_mm3=float(raw.volume),
                           carrier=evidence))
        print(name,row['panel'],evidence['fin_count'],'fins',evidence['starter_rib_count'],'starter ribs',flush=True)
    files['Metadata/model_settings.config']=xml(cfg)
    unchanged=[n for n in before if n not in changed+['Metadata/model_settings.config']]
    assert all(before[n]==files[n] for n in unchanged)
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as z:
        for n,v in files.items():z.writestr(n,v)
    stage['native_slice_validated']=False;stage['carrier_revision']='clean-trim-coupon-v1'
    save_json(path.with_suffix('.json'),stage);save_json(seating_path,seating)
    return dict(project=path.name,sha256=sha(path),changed_child_assets=changed,
                all_other_child_assets_and_saved_poses_byte_identical=True,panels=checks)


if __name__=='__main__':
    reports=[refresh('M-Veneer-'+kind+'-Coupon-A1') for kind in ['Glue','Seam']]
    save_json(OUT/'M-clean-trim-carrier-validation.json',dict(
        revision='clean-trim-coupon-v1',projects=reports,physical_removal_confirmation_pending=True,
        production_A2L_veneers_unchanged_and_on_hold=True))
